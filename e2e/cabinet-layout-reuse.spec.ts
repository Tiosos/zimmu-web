import { expect, test } from '@playwright/test'

test('copies a cabinet layout, replaces it, pastes it back with new drawer boxes and undoes the paste separately', async ({
  page,
}) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '+ Board' })).toBeEnabled({ timeout: 120_000 })
  await page.getByLabel('Add cabinet').click()
  await page.getByRole('option', { name: 'Base 600', exact: true }).click()
  await page.locator('[data-testid^="node-cmp_"]').filter({ hasText: 'Base 600' }).first().click()
  await page.locator('[data-testid^="section-cell-"]').first().click()
  const tools = page.getByRole('region', { name: 'Opening design tools', exact: true })
  const cells = page.locator('[data-testid^="section-cell-"]')
  const drawers = page.locator('[data-testid^="node-cmp_"]').filter({ hasText: /Drawer/ })
  await tools.getByRole('combobox', { name: 'Opening layout', exact: true }).selectOption('drawers')
  await tools.getByRole('button', { name: 'Preview opening layout', exact: true }).click()
  await tools.getByRole('button', { name: 'Apply opening layout', exact: true }).click()
  await expect(drawers).toHaveCount(3)
  const original = await cells.first().getAttribute('data-testid')
  await tools.getByRole('button', { name: 'Copy opening design', exact: true }).click()
  await tools
    .getByRole('combobox', { name: 'Opening layout', exact: true })
    .selectOption('double-door')
  await tools.getByRole('button', { name: 'Preview opening layout', exact: true }).click()
  await tools.getByRole('button', { name: 'Apply opening layout', exact: true }).click()
  await expect(drawers).toHaveCount(0)
  await tools.getByRole('button', { name: 'Paste opening layout', exact: true }).click()
  await expect(drawers).toHaveCount(3)
  await expect(cells).toHaveCount(3)
  await expect(cells.first()).not.toHaveAttribute('data-testid', original!)
  await page.getByRole('button', { name: 'File ▾', exact: true }).click()
  await page.getByRole('button', { name: /Undo "Paste opening layout"/ }).click()
  await expect(drawers).toHaveCount(0)
  await expect(cells).toHaveCount(1)
})

test('navigates openings, reuses fronts without copying shelving and mirrors the group with independent undo', async ({
  page,
}) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '+ Board' })).toBeEnabled({ timeout: 120_000 })
  await page.getByLabel('Add cabinet').click()
  await page.getByRole('option', { name: 'Base 600', exact: true }).click()
  await page.locator('[data-testid^="node-cmp_"]').filter({ hasText: 'Base 600' }).first().click()
  await page.locator('[data-testid^="section-cell-"]').first().click()
  const tools = page.getByRole('region', { name: 'Opening design tools', exact: true })
  const cells = page.locator('[data-testid^="section-cell-"]')
  const drawers = page.locator('[data-testid^="node-cmp_"]').filter({ hasText: /Drawer/ })
  await tools
    .getByRole('combobox', { name: 'Opening layout', exact: true })
    .selectOption('drawer-door')
  await tools.getByRole('button', { name: 'Preview opening layout', exact: true }).click()
  await tools.getByRole('button', { name: 'Apply opening layout', exact: true }).click()
  await expect(drawers).toHaveCount(1)
  await tools.getByRole('button', { name: 'Next opening', exact: true }).click()
  const first = await cells.first().getAttribute('data-testid')
  await expect(tools.getByRole('button', { name: 'Previous opening', exact: true })).toBeDisabled()
  await tools.getByRole('button', { name: 'Copy opening design', exact: true }).click()
  await tools.getByRole('button', { name: 'Next opening', exact: true }).click()
  await expect(tools.getByRole('button', { name: 'Next opening', exact: true })).toBeDisabled()
  await tools.getByRole('button', { name: 'Paste opening front', exact: true }).click()
  await expect(drawers).toHaveCount(0)
  await tools.getByRole('button', { name: 'Repeat shelving to siblings', exact: true }).click()
  await tools.getByRole('button', { name: 'Lock current opening sizes', exact: true }).click()
  await tools.getByRole('button', { name: 'Edit parent opening', exact: true }).click()
  await tools.getByRole('button', { name: 'Mirror opening top/bottom', exact: true }).click()
  await expect(cells.last()).toHaveAttribute('data-testid', first!)
  await page.getByRole('button', { name: 'File ▾', exact: true }).click()
  await page.getByRole('button', { name: /Undo "Mirror opening top\/bottom"/ }).click()
  await expect(cells.first()).toHaveAttribute('data-testid', first!)
  await tools.getByRole('button', { name: 'Equalize nested openings', exact: true }).click()
  await tools.getByRole('button', { name: 'Next opening', exact: true }).click()
  await expect(tools.getByText('Clear opening: 564 × 292 mm (width × height).')).toBeVisible()
})
